def _idx(d):
    return [i for i, b in enumerate(BARS) if b["d"] == d][0]


def _verdict_at(d):
    """截至 d 收盘（含）的 top_verdict。"""
    i = _idx(d)
    return TS.top_verdict(BARS[:i + 1], live_last=False)


def _sma(i, k):
    return sum(b["c"] for b in BARS[i + 1 - k:i + 1]) / k


def _ema(i, k):
    kk = 2 / (k + 1)
    e = BARS[0]["c"]
    for j in range(1, i + 1):
        e = BARS[j]["c"] * kk + e * (1 - kk)
    return e


