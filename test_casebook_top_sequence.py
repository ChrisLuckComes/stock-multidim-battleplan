def test_the_mismatch_between_four_reqs_and_wave_high():
    """★★ 核心元结论：**四要件齐备 ≠ 波峰；波峰 ≠ 四要件齐备**。

    四个案例里唯一四要件全齐的那一根（石头 06-23）恰恰不是波峰；
    而三个真波峰（顺丰 02-18、茅台 02-18、隆基 07-01 一侧）四要件都不齐。
    """
    rows = [
        ("隆基", LJ_BARS_LIKE, "2022-07-08", False, 1),
        ("顺丰", SF_BARS, SF_TOP, True, 1),
        ("茅台", MT_BARS, MT_TOP, True, 1),
        ("石头", ST_BARS, ST_CRASH, False, 3),
    ]
    for name, bars, d, is_wave, n_req in rows:
        i = _idx(bars, d)
        wh = TS.is_wave_high(bars, i, atr_v=TS.atr(bars[:i + 1]))["ok"]
        got = sum(_guillotine_reqs(bars, i))
        assert wh is is_wave, f"{name} 波峰判定不符"
        assert got == n_req, f"{name} 四要件命中数应为 {n_req}，实际 {got}"
    # 反向断言：真波峰的案例里，没有一个是四要件齐备的
    for name, bars, d, is_wave, _n in rows:
        if is_wave:
            assert sum(_guillotine_reqs(bars, _idx(bars, d))) < 3
    # 而四要件齐备的那个（石头 06-23）不是波峰
    assert sum(_guillotine_reqs(ST_BARS, _idx(ST_BARS, ST_CRASH))) == 3
    assert TS.is_wave_high(ST_BARS, _idx(ST_BARS, ST_CRASH),
                           atr_v=TS.atr(ST_BARS[: _idx(ST_BARS, ST_CRASH) + 1]))["ok"] is False


